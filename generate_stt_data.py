def main():
    parser = argparse.ArgumentParser(description="Scenario-Wise STT Dataset Generator")
    parser.add_argument("--lang", required=True, choices=list(SUPPORTED_LANGUAGES.keys()), help="Target dataset primary language")
    parser.add_argument("--limit", type=int, default=100, help="Total number of text utterances to generate")
    parser.add_argument("--output-dir", default="stt_dataset", help="Output directory path")
    parser.add_argument("--synthesize", action="store_true", help="Synthesize audio files using gTTS")
    
    args = parser.parse_args()
    
    lang = args.lang
    output_dir = Path(args.output_dir) / lang
    output_dir.mkdir(parents=True, exist_ok=True)
    
    metadata_file = output_dir / f"metadata_{lang}.csv"
    audio_dir = output_dir / "audio"
    
    # Conditionally import gTTS if synthesizing is requested
    gTTS_module = None
    if args.synthesize:
        audio_dir.mkdir(parents=True, exist_ok=True)
        try:
            from gtts import gTTS
            gTTS_module = gTTS
            logger.info("gTTS module loaded successfully.")
        except ImportError:
            logger.error("gTTS package is not installed. Run 'pip install gTTS' to enable audio synthesis.")
            logger.info("Proceeding with metadata/text generation only.")
            args.synthesize = False

    # Build target count distributions per scenario
    scenario_counts = {}
    remaining = args.limit
    
    for sc, weight in SCENARIO_WEIGHTS.items():
        count = int(round(args.limit * weight))
        scenario_counts[sc] = max(1, count)
        remaining -= scenario_counts[sc]
        
    # Adjust to fit exact limit
    if remaining != 0:
        keys = list(SCENARIO_WEIGHTS.keys())
        for _ in range(abs(remaining)):
            idx = random.randint(0, len(keys) - 1)
            if remaining > 0:
                scenario_counts[keys[idx]] += 1
            else:
                if scenario_counts[keys[idx]] > 1:
                    scenario_counts[keys[idx]] -= 1

    logger.info(f"Generating {args.limit} utterances for '{SUPPORTED_LANGUAGES[lang]['name']}' ({lang}).")
    
    dataset_records = []
    index = 1
    
    for scenario_name, count in scenario_counts.items():
        logger.info(f"Generating {count} utterances for scenario '{scenario_name}'...")
        for _ in range(count):
            transcript, native, roman, code_mixed = generate_scenario_sentence_parallel(lang, scenario_name)
            
            audio_filename = f"{lang}_{scenario_name}_{index:05d}.mp3"
            audio_path = audio_dir / audio_filename
            relative_audio_path = f"audio/{audio_filename}"
            
            duration = 0.0
            
            # Synthesize Audio if requested
            if args.synthesize and gTTS_module:
                try:
                    tts = gTTS_module(text=transcript, lang=SUPPORTED_LANGUAGES[lang]["tts_code"])
                    tts.save(str(audio_path))
                    # Estimate duration based on word count (approx 150 words per minute)
                    words = len(transcript.split())
                    duration = round(max(1.5, (words / 150.0) * 60.0), 2)
                    time.sleep(0.05) # Small delay to avoid rate limits
                except Exception as e:
                    logger.error(f"TTS synthesis failed for index {index}: {e}")
                    duration = 0.0
                    
            record = {
                "id": f"{lang}_{index:05d}",
                "audio_path": relative_audio_path if args.synthesize else "N/A",
                "transcript": transcript,
                "native_text": native,
                "romanized_text": roman,
                "code_mixed_text": code_mixed,
                "scenario": scenario_name,
                "language": lang,
                "duration_seconds": duration
            }
            dataset_records.append(record)
            index += 1

    # Write CSV metadata output
    logger.info(f"Writing metadata to {metadata_file}...")
    try:
        with open(metadata_file, "w", encoding="utf-8", newline="") as f:
            fieldnames = ["id", "audio_path", "transcript", "native_text", "romanized_text", "code_mixed_text", "scenario", "language", "duration_seconds"]
            writer = csv.DictWriter(f, fieldnames=fieldnames)
            writer.writeheader()
            writer.writerows(dataset_records)
        logger.info(f"Metadata file generated successfully at {metadata_file}!")
    except Exception as e:
        logger.error(f"Failed to write metadata file: {e}")


if __name__ == "__main__":
    main()
