def transliterate_to_roman(text: str, lang: str) -> str:
    if lang == "en":
        return text
    res = []
    for i, c in enumerate(text):
        val = ord(c)
        if 0x0900 <= val <= 0x0d7f:
            base = val & ~0x7f
            offset = val - base
            if 0x15 <= offset <= 0x39:
                has_matra = False
                if i + 1 < len(text):
                    next_val = ord(text[i+1])
                    next_offset = next_val - (next_val & ~0x7f)
                    if 0x3e <= next_offset <= 0x4d:
                        has_matra = True
                char_str = BRAHMIC_MAP.get(offset, '')
                if not has_matra and char_str:
                    res.append(char_str + 'a')
                else:
                    res.append(char_str)
            else:
                res.append(BRAHMIC_MAP.get(offset, ''))
        else:
            res.append(c)
    result = "".join(res)
    result = re.sub(r'\s+', ' ', result).strip()
    result = re.sub(r'[।|.]', '', result).strip()
    return result

def digit_sequence_to_spoken(digits: str) -> str:
    """Converts a digit string (e.g. '3345') to a diverse spoken word sequence with double/triple patterns."""
    runs = []
    i = 0
    n = len(digits)
    while i < n:
        char = digits[i]
        run_len = 1
        while i + run_len < n and digits[i + run_len] == char:
            run_len += 1
        runs.append((char, run_len))
        i += run_len

    run_words = []
    for char, length in runs:
        digit_name = {"0":"zero","1":"one","2":"two","3":"three","4":"four","5":"five","6":"six","7":"seven","8":"eight","9":"nine"}[char]
        if length == 1:
            run_words.append(digit_name)
        elif length == 2:
            if random.random() < 0.6:  # 60% chance of "double X"
                run_words.append(f"double {digit_name}")
            else:
                run_words.append(f"{digit_name} {digit_name}")
        elif length == 3:
            r = random.random()
            if r < 0.5:  # 50% chance of "triple X"
                run_words.append(f"triple {digit_name}")
            elif r < 0.75:  # 25% chance of "double X X"
                run_words.append(f"double {digit_name} {digit_name}")
            elif r < 0.9:  # 15% chance of "X double X"
                run_words.append(f"{digit_name} double {digit_name}")
            else:
                run_words.append(f"{digit_name} {digit_name} {digit_name}")
        else:
            words = [digit_name] * length
            run_words.append(" ".join(words))
            
    return " ".join(run_words)

